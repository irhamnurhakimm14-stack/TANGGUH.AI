"""PostgreSQL storage; used only with configured cloud credentials."""
from contextlib import contextmanager
from io import BytesIO
import os, hashlib
from PIL import Image, ImageOps

@contextmanager
def connect():
    import psycopg
    from psycopg.rows import dict_row
    with psycopg.connect(os.environ["DATABASE_URL"],row_factory=dict_row,connect_timeout=10) as conn:
        class Adapter:
            def execute(self,query,params=()):
                return conn.execute(query.replace("?", "%s"),params)
        yield Adapter()

def initialize(schema):
    with connect() as con:
        con.execute("SELECT pg_advisory_xact_lock(83170321)")
        # Remove SQL comments before splitting; comments may contain semicolons.
        schema="\n".join(line.split("--",1)[0] for line in schema.splitlines())
        for statement in schema.replace("INTEGER PRIMARY KEY AUTOINCREMENT","INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY").split(";"):
            if statement.strip(): con.execute(statement)
        con.execute("CREATE TABLE IF NOT EXISTS tangguh_photos (name TEXT PRIMARY KEY, content BYTEA NOT NULL)")

def prepare_photo(stream):
    raw=stream.read(3*1024*1024+1)
    if len(raw)>3*1024*1024: raise ValueError("Maksimum foto 3 MB.")
    try:
        with Image.open(BytesIO(raw)) as image:
            if image.format not in {"JPEG","PNG","WEBP"} or image.width*image.height>25_000_000: raise ValueError("Format atau ukuran piksel tidak didukung.")
            rgb=ImageOps.exif_transpose(image).convert("RGB")
            rgb.thumbnail((1600,1600))
            out=BytesIO(); rgb.save(out,format="JPEG",quality=85)
    except (OSError,Image.DecompressionBombError) as exc: raise ValueError("Foto tidak valid.") from exc
    data=out.getvalue()
    return hashlib.sha256(data).hexdigest()+".jpg",data

def save_photo(stream):
    name,data=prepare_photo(stream)
    with connect() as con: con.execute("INSERT INTO tangguh_photos (name,content) VALUES (?,?) ON CONFLICT (name) DO NOTHING",(name,data))
    return name

def load_photo(name):
    with connect() as con: row=con.execute("SELECT content FROM tangguh_photos WHERE name=?",(name,)).fetchone()
    return bytes(row["content"]) if row else None
